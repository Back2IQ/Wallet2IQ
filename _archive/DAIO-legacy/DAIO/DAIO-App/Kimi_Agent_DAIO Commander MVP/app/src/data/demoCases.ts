// Calculate weighted average risk
export const calculateWeightedRisk = (): number => {
  const { crypto, nft, gaming } = demoStats.assetDistribution;
  const { crypto: cryptoRisk, nft: nftRisk, gaming: gamingRisk } = demoStats.riskWeights;
  
  return (crypto * cryptoRisk + nft * nftRisk + gaming * gamingRisk) / 100;
};

// Generate loss estimator data
export const generateLossEstimatorData = () => {
  const totalValue = demoCases.reduce((sum, c) => sum + c.totalValue, 0);
  const totalCrypto = demoCases.reduce((sum, c) => sum + c.cryptoValue, 0);
  const totalNFT = demoCases.reduce((sum, c) => sum + c.nftValue, 0);
  const totalGaming = demoCases.reduce((sum, c) => sum + c.gamingValue, 0);
  
  const weightedRisk = calculateWeightedRisk();
  
  return {
    totalCases: demoCases.length,
    averageWealth: Math.round(totalValue / demoCases.length),
    assetDistribution: {
      crypto: Math.round((totalCrypto / totalValue) * 100),
      nft: Math.round((totalNFT / totalValue) * 100),
      gaming: Math.round((totalGaming / totalValue) * 100),
    },
    riskWithoutStructure: Math.round(weightedRisk * 100),
    potentialLossGermany: demoStats.potentialAnnualLoss,
    potentialSaved: demoStats.potentialSavedWithDAIO,
  };
};
